package com.ramzmania.tubefy.probe

import com.ramzmania.tubefy.core.extractors.newpipeextractor.PipeDownloader
import okhttp3.OkHttpClient
import okhttp3.Request
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList

/** Manual: which formats / audio tracks / captions YouTube gives; runs only with env TUBEFY_PROBE=true. */
class StreamFormatsProbe {
    @Test
    fun probe() {
        assumeTrue(System.getenv("TUBEFY_PROBE") == "true")
        val http = OkHttpClient()
        NewPipe.init(PipeDownloader(http))
        // a normal music video, a multi-language-audio video (MrBeast), a talk with captions
        for (id in listOf("O5gwxm3NxFU", "0e3GPea1Tyg", "8jPQjjsBbIc")) {
            val ex = ServiceList.YouTube.getStreamExtractor("https://www.youtube.com/watch?v=$id")
            ex.fetchPage()
            println("== $id '${ex.name.take(40)}' hls=${ex.hlsUrl.isNotBlank()} dash=${ex.dashMpdUrl.isNotBlank()} dur=${ex.length}")
            ex.videoStreams.forEach { println("  MUXED ${it.resolution} ${it.format} itag=${it.itag} method=${it.deliveryMethod}") }
            ex.videoOnlyStreams.take(30).forEach {
                val i = it.itagItem
                println("  VIDEO ${it.resolution} ${it.format} itag=${it.itag} codec=${it.codec} method=${it.deliveryMethod} init=${i?.initStart}-${i?.initEnd} index=${i?.indexStart}-${i?.indexEnd} len=${i?.contentLength} bitrate=${i?.bitrate}")
            }
            ex.audioStreams.forEach {
                val i = it.itagItem
                println("  AUDIO ${it.format} itag=${it.itag} br=${it.averageBitrate} track=${it.audioTrackId}/${it.audioTrackName}/${it.audioLocale}/${it.audioTrackType} method=${it.deliveryMethod} init=${i?.initStart}-${i?.initEnd} index=${i?.indexStart}-${i?.indexEnd}")
            }
            ex.subtitlesDefault.forEach { println("  SUB ${it.languageTag} ${it.format} auto=${it.isAutoGenerated} name=${it.displayLanguageName}") }
            // can we actually fetch them?
            fun status(url: String?, range: Boolean = true): String = if (url.isNullOrBlank()) "-" else runCatching {
                http.newCall(Request.Builder().url(url).apply { if (range) header("Range", "bytes=0-999") }.header("User-Agent", "Mozilla/5.0").build()).execute().use { "${it.code} ${it.body?.contentLength()}" }
            }.getOrElse { it.javaClass.simpleName }
            ex.subtitlesDefault.filter { it.languageTag.startsWith("en") }.take(2).forEach { sub ->
                val body = runCatching { http.newCall(Request.Builder().url(sub.content).header("User-Agent", "Mozilla/5.0").build()).execute().use { "${it.code} ${it.body?.string()?.let { b -> b.length.toString() + " chars: " + b.take(160).replace("\n", " ") }}" } }.getOrElse { it.toString() }
                println("  SUBFETCH ${sub.languageTag} auto=${sub.isAutoGenerated} -> $body")
            }
            println("  FETCH video=${status(ex.videoOnlyStreams.firstOrNull { it.resolution == "720p" }?.content)} audio=${status(ex.audioStreams.firstOrNull()?.content)} " +
                "sub=${status(ex.subtitlesDefault.firstOrNull { it.format?.suffix == "vtt" }?.content, range = false)} hls=${status(ex.hlsUrl, range = false)}")
        }
    }
}
