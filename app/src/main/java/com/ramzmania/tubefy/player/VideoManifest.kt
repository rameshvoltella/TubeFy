package com.ramzmania.tubefy.player

import com.ramzmania.tubefy.core.YoutubeCoreConstant
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.services.youtube.YoutubeService
import org.schabi.newpipe.extractor.services.youtube.extractors.YoutubeStreamExtractor
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.AudioTrackType
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.VideoStream

/**
 * Builds a DASH manifest for a YouTube video from NewPipe's separate video and audio streams, so the
 * player can offer every quality (144p–1080p) and every audio language, and switch between them
 * without reloading. (The single "muxed" file the songs use only goes up to 360p.)
 */
object VideoManifest {

    private const val TAG = "VideoManifest"

    /**
     * Whether VP9 may be used. Set from the device's decoders (see [hasHardwareVp9]): many TV boxes
     * can't play VP9 smoothly, and a failing video falls back to the single 360p file (no qualities).
     */
    @Volatile var allowVp9: Boolean = true

    /** True when the device has a hardware VP9 decoder. */
    fun hasHardwareVp9(): Boolean = runCatching {
        android.media.MediaCodecList(android.media.MediaCodecList.REGULAR_CODECS).codecInfos.any { info ->
            !info.isEncoder &&
                info.supportedTypes.any { it.equals("video/x-vnd.on2.vp9", ignoreCase = true) } &&
                (android.os.Build.VERSION.SDK_INT < android.os.Build.VERSION_CODES.Q || info.isHardwareAccelerated)
        }
    }.getOrDefault(false)

    data class Representation(
        val id: String,
        val url: String,
        val mimeType: String,
        val codecs: String,
        val bandwidth: Int,
        val initRange: LongRange,
        val indexRange: LongRange,
        val width: Int = 0,
        val height: Int = 0,
        val fps: Int = 0
    )

    data class AudioTrack(
        /** BCP-47 language, e.g. "en-US"; null for videos with a single audio track. */
        val language: String?,
        /** e.g. "English (US) original", "Hindi". */
        val label: String?,
        val original: Boolean,
        val representations: List<Representation>
    )

    data class Subtitle(val url: String, val language: String, val label: String, val autoGenerated: Boolean)

    class Result(val manifest: String, val subtitles: List<Subtitle>, val title: String, val uploader: String)

    /**
     * Fetches [videoId]'s streams and builds its manifest; null for videos that can't be played this
     * way (live streams, or no separate streams with index ranges).
     */
    fun fetch(videoId: String): Result? {
        val extractor = YoutubeService(0)
            .getStreamExtractor("${YoutubeCoreConstant.YOUTUBE_WATCH_URL}$videoId") as YoutubeStreamExtractor
        extractor.fetchPage()
        val duration = extractor.length
        if (duration <= 0) return null // live

        val video = pickVideo(extractor.videoOnlyStreams, allowVp9)
        val audio = pickAudio(extractor.audioStreams)
        if (video.isEmpty() || audio.isEmpty()) {
            android.util.Log.w(TAG, "$videoId: no adaptive streams (video=${video.size}, audio=${audio.size})")
            return null
        }
        android.util.Log.i(
            TAG,
            "$videoId: ${video.first().mimeType} ${video.joinToString { "${it.height}p" }}, ${audio.size} audio track(s), vp9 allowed=$allowVp9"
        )

        val subtitles = extractor.subtitlesDefault.orEmpty()
            .filter { !it.content.isNullOrBlank() && it.format == MediaFormat.TTML }
            .distinctBy { it.languageTag + it.isAutoGenerated }
            .map { sub ->
                val name = sub.displayLanguageName?.takeIf { it.isNotBlank() } ?: sub.languageTag
                Subtitle(sub.content, sub.languageTag, if (sub.isAutoGenerated) "$name (auto-generated)" else name, sub.isAutoGenerated)
            }
            .sortedBy { it.autoGenerated }
        return Result(build(duration, video, audio), subtitles, extractor.name.orEmpty(), extractor.uploaderName.orEmpty())
    }

    /** One codec family only (mixing codecs breaks quality switching), every resolution. */
    private fun pickVideo(streams: List<VideoStream>, allowVp9: Boolean): List<Representation> {
        val usable = streams.mapNotNull { stream ->
            val itag = stream.itagItem ?: return@mapNotNull null
            if (stream.deliveryMethod != DeliveryMethod.PROGRESSIVE_HTTP || itag.indexEnd <= 0 || itag.initEnd <= 0) return@mapNotNull null
            val mime = stream.format?.mimeType ?: return@mapNotNull null
            Representation(
                id = "v${stream.itag}",
                url = stream.content,
                mimeType = mime,
                codecs = stream.codec.orEmpty(),
                bandwidth = itag.bitrate,
                initRange = itag.initStart.toLong()..itag.initEnd.toLong(),
                indexRange = itag.indexStart.toLong()..itag.indexEnd.toLong(),
                width = stream.width,
                height = stream.height,
                fps = stream.fps
            )
        }
        // The family that reaches the highest resolution (H.264 on a tie: it plays everywhere).
        // WebM (VP9) only when the device decodes it in hardware.
        val family = usable.filter { allowVp9 || it.mimeType == "video/mp4" }.ifEmpty { usable }
            .groupBy { it.mimeType }
            .maxWithOrNull(compareBy<Map.Entry<String, List<Representation>>> { entry -> entry.value.maxOf { it.height } }
                .thenBy { if (it.key == "video/mp4") 1 else 0 })
            ?.value.orEmpty()
        return family.distinctBy { it.height }.sortedByDescending { it.height }
    }

    /** The best stream of every audio language (M4A where possible). */
    private fun pickAudio(streams: List<AudioStream>): List<AudioTrack> = streams
        .filter { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && (it.itagItem?.indexEnd ?: 0) > 0 }
        .groupBy { it.audioTrackId }
        .mapNotNull { (_, group) ->
            val best = group.filter { it.format == MediaFormat.M4A }.maxByOrNull { it.averageBitrate }
                ?: group.maxByOrNull { it.averageBitrate }
                ?: return@mapNotNull null
            val itag = best.itagItem ?: return@mapNotNull null
            AudioTrack(
                language = best.audioLocale?.toLanguageTag()?.takeIf { it.isNotBlank() && it != "und" },
                label = best.audioTrackName,
                original = best.audioTrackType == null || best.audioTrackType == AudioTrackType.ORIGINAL,
                representations = listOf(
                    Representation(
                        id = "a${best.itag}-${best.audioTrackId ?: "main"}",
                        url = best.content,
                        mimeType = best.format?.mimeType ?: "audio/mp4",
                        codecs = best.codec.orEmpty(),
                        bandwidth = itag.bitrate,
                        initRange = itag.initStart.toLong()..itag.initEnd.toLong(),
                        indexRange = itag.indexStart.toLong()..itag.indexEnd.toLong()
                    )
                )
            )
        }
        // Original first, then by name
        .sortedWith(compareByDescending<AudioTrack> { it.original }.thenBy { it.label.orEmpty() })

    /** The manifest XML: one video set with all qualities, one audio set per language. */
    fun build(durationSeconds: Long, video: List<Representation>, audio: List<AudioTrack>): String = buildString {
        append("""<?xml version="1.0" encoding="UTF-8"?>""").append('\n')
        append("""<MPD xmlns="urn:mpeg:dash:schema:mpd:2011" profiles="urn:mpeg:dash:profile:isoff-on-demand:2011" """)
        append("""type="static" minBufferTime="PT1.5S" mediaPresentationDuration="PT${durationSeconds}S">""").append('\n')
        append("<Period>\n")
        var setId = 0
        if (video.isNotEmpty()) {
            append("""<AdaptationSet id="${setId++}" contentType="video" mimeType="${video.first().mimeType}" subsegmentAlignment="true">""").append('\n')
            video.forEach { rep ->
                append("""<Representation id="${xml(rep.id)}" bandwidth="${rep.bandwidth}" codecs="${xml(rep.codecs)}" width="${rep.width}" height="${rep.height}"""")
                if (rep.fps > 0) append(""" frameRate="${rep.fps}"""")
                append(">\n")
                appendBody(rep)
                append("</Representation>\n")
            }
            append("</AdaptationSet>\n")
        }
        audio.forEach { track ->
            val first = track.representations.firstOrNull() ?: return@forEach
            append("""<AdaptationSet id="${setId++}" contentType="audio" mimeType="${first.mimeType}" subsegmentAlignment="true"""")
            track.language?.let { append(""" lang="${xml(it)}"""") }
            append(">\n")
            // "main" = the original audio (picked by default), "dub" = a dubbed language
            append("""<Role schemeIdUri="urn:mpeg:dash:role:2011" value="${if (track.original) "main" else "dub"}"/>""").append('\n')
            track.label?.let { append("<Label>${xml(it)}</Label>\n") }
            track.representations.forEach { rep ->
                append("""<Representation id="${xml(rep.id)}" bandwidth="${rep.bandwidth}" codecs="${xml(rep.codecs)}">""").append('\n')
                append("""<AudioChannelConfiguration schemeIdUri="urn:mpeg:dash:23003:3:audio_channel_configuration:2011" value="2"/>""").append('\n')
                appendBody(rep)
                append("</Representation>\n")
            }
            append("</AdaptationSet>\n")
        }
        append("</Period>\n</MPD>\n")
    }

    private fun StringBuilder.appendBody(rep: Representation) {
        append("<BaseURL>${xml(rep.url)}</BaseURL>\n")
        append("""<SegmentBase indexRange="${rep.indexRange.first}-${rep.indexRange.last}">""")
        append("""<Initialization range="${rep.initRange.first}-${rep.initRange.last}"/></SegmentBase>""").append('\n')
    }

    private fun xml(value: String) = value
        .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;").replace("'", "&apos;")
}
